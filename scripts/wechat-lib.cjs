// The WeChat mini program's libraries, bundled as CommonJS (as mini programs load modules):
//   wechat/lib/core.js          engine, device source and stream for all pages (src/wechat/core.ts)
//   wechat/lib/openbci.js       the phone app's packet parser (src/engine-ts/openbci.ts)
//   wechat/moment/lib/card.js  the 脑电记录 card (src/wechat/card.ts: the desktop's momentCard)
//   wechat/lib/jsqr.js          QR detection with corner points, for the scanner's frame (jsQR)
// The developer tool compiles nothing (project.config.json), so the bundle is lowered to ES2017
// here.
const path = require('path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');

const lib = (entry, out, extra = {}) =>
  esbuild.build({
    entryPoints: [path.join(root, entry)],
    bundle: true,
    format: 'cjs',
    target: 'es2017',
    outfile: path.join(root, 'wechat', out),
    banner: { js: `// Generated by scripts/wechat-lib.cjs from ${entry}. Do not edit.` },
    logLevel: 'warning',
    ...extra,
  });

Promise.all([
  lib('src/engine-ts/openbci.ts', 'lib/openbci.js'),
  lib('src/wechat/core.ts', 'lib/core.js', { minify: true, legalComments: 'none' }),
  lib('node_modules/jsqr/dist/jsQR.js', 'lib/jsqr.js', { minify: true, legalComments: 'none' }),
  // the 脑电记录 card (its pictures' assets: the star catalogue inlined, the brain image copied)
  lib('src/wechat/card.ts', 'moment/lib/card.js', {
    minify: true,
    legalComments: 'none',
    loader: { '.png': 'empty' },
  }),
]).catch(() => process.exit(1));
