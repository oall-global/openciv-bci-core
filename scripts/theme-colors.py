"""Turn the colour literals in src/**/*.css into theme variables (one-off, re-runnable).

Every literal in a colour property becomes var(--t-<role>-<hex>[-a<alpha>]); the light value
is the literal itself (the light theme is unchanged), the dark value is derived by role:
  bg  light surfaces -> dark surfaces of the same hue family (tint kept, low lightness)
  bd  light borders  -> dark lines (tinted borders stay tinted)
  fg  dark text      -> light text; coloured text keeps its hue (status colours unchanged)
Writes src/theme-colors.css (the variables) and rewrites the stylesheets in place.
"""

import colorsys
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {"tokens.css", "theme-colors.css"}
PROPS = re.compile(
    r"^(\s*)(background(?:-color|-image)?|border(?:-top|-right|-bottom|-left)?(?:-color)?|"
    r"outline(?:-color)?|color|fill|stroke|box-shadow|text-shadow|caret-color|accent-color|"
    r"text-decoration-color|column-rule-color)(\s*:\s*)([^;{}]+)(;?)",
    re.M,
)
COLOR = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+\s*(?:,\s*[\d.]+\s*)?\)|\bwhite\b")


def parse(c):
    c = c.strip().lower()
    if c == "white":
        return (255, 255, 255, 1.0)
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(x * 2 for x in h)
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0)
    parts = [float(x) for x in c[c.index("(") + 1 : -1].split(",")]
    return (int(parts[0]), int(parts[1]), int(parts[2]), parts[3] if len(parts) > 3 else 1.0)


def lum(r, g, b):
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255


def hls(r, g, b):
    return colorsys.rgb_to_hls(r / 255, g / 255, b / 255)


def rgb(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return (round(r * 255), round(g * 255), round(b * 255))


def dark(role, r, g, b):
    L = lum(r, g, b)
    h, l, s = hls(r, g, b)
    if role == "bg":
        if L <= 0.78:
            return (r, g, b)  # already a strong colour (buttons, bars): keep
        if s < 0.12 or l > 0.985:
            return (17, 23, 21) if L > 0.97 else (24, 32, 29)  # paper / raised
        return rgb(h, 0.13, min(s, 0.4))
    if role == "bd":
        if L <= 0.7:
            return (r, g, b)
        if s < 0.15:
            return (35, 46, 42)
        return rgb(h, 0.24, min(s, 0.4))
    # fg
    if L >= 0.55:
        return (r, g, b)
    if s < 0.18:
        return (230, 238, 234) if L < 0.3 else (160, 175, 168)
    return rgb(h, 0.7, min(1.0, s))


def role_of(prop):
    if prop.startswith("border") or prop.startswith("outline") or prop.startswith("column-rule"):
        return "bd"
    if prop.startswith("background") or prop in ("box-shadow",):
        return "bg"
    return "fg"


tokens = {}


def token(role, lit):
    r, g, b, a = parse(lit)
    d = dark(role, r, g, b)
    if d == (r, g, b):
        return None  # same in both themes: leave the literal
    name = f"--t-{role}-{r:02x}{g:02x}{b:02x}" + (f"-a{round(a * 100)}" if a < 1 else "")
    light = f"rgba({r}, {g}, {b}, {a:g})" if a < 1 else f"#{r:02x}{g:02x}{b:02x}"
    darkv = f"rgba({d[0]}, {d[1]}, {d[2]}, {a:g})" if a < 1 else f"#{d[0]:02x}{d[1]:02x}{d[2]:02x}"
    tokens[name] = (light, darkv)
    return f"var({name})"


def rewrite(text):
    def decl(m):
        indent, prop, colon, value, semi = m.groups()
        if "var(--t-" in value:
            return m.group(0)
        role = role_of(prop)
        new = COLOR.sub(lambda c: token(role, c.group(0)) or c.group(0), value)
        return f"{indent}{prop}{colon}{new}{semi}"

    return PROPS.sub(decl, text)


def main():
    files = [p for p in (ROOT / "src").rglob("*.css") if p.name not in SKIP]
    changed = 0
    for p in files:
        raw = p.read_text(encoding="utf-8")
        crlf = "\r\n" in raw
        text = raw.replace("\r\n", "\n")
        new = rewrite(text)
        if new != text:
            changed += 1
            p.write_text(new.replace("\n", "\r\n") if crlf else new, encoding="utf-8", newline="")
    # Keep variables from earlier runs (their literals are already replaced).
    out = ROOT / "src" / "theme-colors.css"
    if out.exists():
        for name, light, darkv in re.findall(
            r"(--t-[\w-]+): ([^;]+); /\* dark: ([^*]+) \*/", out.read_text(encoding="utf-8")
        ):
            tokens.setdefault(name, (light, darkv.strip()))
    lines = [
        "/* Generated by scripts/theme-colors.py: colour literals of the stylesheets as theme",
        "   variables. Light values are the original literals; dark values are derived by role. */",
        ":root {",
    ]
    for name in sorted(tokens):
        light, darkv = tokens[name]
        lines.append(f"  {name}: {light}; /* dark: {darkv} */")
    lines += ["}", ":root[data-theme='dark'] {"]
    for name in sorted(tokens):
        lines.append(f"  {name}: {tokens[name][1]};")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{changed} stylesheets, {len(tokens)} variables", file=sys.stderr)


main()
