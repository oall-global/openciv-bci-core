// Fold the ~500 generated colour variables of src/theme-colors.css onto the few roles of the
// design system (DESIGN.md): surfaces, lines and the soft state fills. Near-identical tints that
// grew page by page (dozens of pale greens and blue-greys) become one token each; saturated
// colours (data series, status marks, illustrations) and translucent ones keep their value.
// Writes src/palette-map.css, which loads after theme-colors.css. Re-runnable:
//   node scripts/palette-map.cjs
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src', 'theme-colors.css'), 'utf8');
const names = [
  ...new Set([...src.matchAll(/--t-(bg|bd|fg)-([0-9a-f]{6})(-a\d+)?(?=:)/g)].map((m) => m[0])),
];

function hsl(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const d = max - min;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  let h = 0;
  if (d) {
    if (max === r) h = 60 * (((g - b) / d) % 6);
    else if (max === g) h = 60 * ((b - r) / d + 2);
    else h = 60 * ((r - g) / d + 4);
  }
  return { h: (h + 360) % 360, s, l };
}

// the hue family of a pale tint
function family(h) {
  if (h < 20 || h >= 330) return 'danger';
  if (h < 70) return 'warn';
  if (h < 175) return 'accent';
  if (h < 260) return 'info';
  return null; // violet: kept
}

function role(name) {
  const [, kind, hex, alpha] = name.match(/--t-(bg|bd|fg)-([0-9a-f]{6})(-a\d+)?/);
  if (alpha) return null;
  const { h, s, l } = hsl(hex);
  const neutral = s < 0.16 || l > 0.97;
  if (kind === 'bg') {
    if (l > 0.985) return 'var(--paper)';
    if (neutral && l > 0.9) return 'var(--surface-2)';
    if (neutral && l > 0.8) return 'var(--surface-3)';
    if (!neutral && l > 0.86) {
      const f = family(h);
      return f ? `var(--${f}-soft)` : null;
    }
    return null;
  }
  if (kind === 'bd') {
    if (l < 0.7) return null;
    if (neutral || l > 0.9) return 'var(--line)';
    const f = family(h);
    return f ? `var(--${f}-line)` : null;
  }
  // text: greys onto the ink ramp; coloured text keeps its hue
  if (s < 0.2) {
    if (l < 0.22) return 'var(--ink)';
    if (l < 0.36) return 'var(--ink2)';
    if (l < 0.48) return 'var(--ink3)';
    return 'var(--ink4)';
  }
  return null;
}

const lines = [];
let kept = 0;
for (const n of names) {
  const r = role(n);
  if (r) lines.push(`  ${n}: ${r};`);
  else kept++;
}
const out = `/* Generated by scripts/palette-map.cjs — do not edit by hand.
   ${lines.length} generated colours folded onto the system roles; ${kept} saturated or translucent
   ones keep their own value (theme-colors.css). */
:root:root:root {
${lines.join('\n')}
}
`;
fs.writeFileSync(path.join(root, 'src', 'palette-map.css'), out);
console.log(`${lines.length} mapped, ${kept} kept`);
